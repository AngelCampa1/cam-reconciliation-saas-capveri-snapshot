const pyStr = (indent, key, value) => {
  const singleLine = `${indent}"${key}": "${value}",`;
  if (singleLine.length <= 88) return singleLine;
  const innerIndent = indent + "    ";
  const innerLine = `${innerIndent}"${value}"`;
  const noqa = innerLine.length > 88 ? "  # noqa: E501" : "";
  return `${indent}"${key}": (\n${innerLine}${noqa}\n${indent}),`;
};

const pyVal = (v) => {
  if (v === null) return "None";
  if (typeof v === "boolean") return v ? "True" : "False";
  return String(v);
};

const pyUnitPricingBands = (bands = []) => {
  if (!bands.length) return "[]";
  return `[\n${bands
    .map((band) =>
      [
        "            {",
        `                "min_units": ${band.minUnits},`,
        `                "max_units": ${pyVal(band.maxUnits)},`,
        `                "price_per_unit_annual": ${band.pricePerUnitAnnual},`,
        "            },",
      ].join("\n"),
    )
    .join("\n")}\n        ]`;
};

