    async def test_complete_signup_updates_profile_to_tenant_role(
        self, service, mock_admin
    ) -> None:
        """Tenant signup rewrites the auth trigger profile into tenant context."""
        invitation_data = make_valid_invitation_data()
        invite_result = MagicMock()
        invite_result.data = [invitation_data]

        mock_user = MagicMock()
        mock_user.id = str(uuid4())
        mock_auth_response = MagicMock()
        mock_auth_response.user = mock_user
        service.supabase_admin.auth.admin.create_user = MagicMock(
            return_value=mock_auth_response
        )

        tenant_user_data = {
            "id": str(uuid4()),
            "user_id": str(mock_user.id),
            "organization_id": invitation_data["organization_id"],
            "contact_name": "John Doe",
            "contact_email": invitation_data["email"],
            "created_at": datetime.now(UTC).isoformat(),
        }
        tenant_user_result = MagicMock()
        tenant_user_result.data = [tenant_user_data]
        write_result = MagicMock()
        write_result.data = [{"ok": True}]

        query_builders: dict[str, MagicMock] = {}

        def table(name: str) -> MagicMock:
            builder = MagicMock()
            query_builders[name] = builder
            if name == "tenant_invitations":
                builder.select.return_value.eq.return_value.execute.return_value = (
                    invite_result
                )
                builder.update.return_value.eq.return_value.execute.return_value = (
                    write_result
                )
            elif name == "tenant_users":
                builder.insert.return_value.execute.return_value = tenant_user_result
            else:
                builder.insert.return_value.execute.return_value = write_result
                builder.upsert.return_value.execute.return_value = write_result
            return builder

        mock_admin.table.side_effect = table

        mock_session = MagicMock()
        mock_session.access_token = "access_token_123"
        mock_session.refresh_token = "refresh_token_456"
        mock_signin_response = MagicMock()
        mock_signin_response.session = mock_session
        service.supabase_admin.auth.sign_in_with_password = MagicMock(
            return_value=mock_signin_response
        )

        await service.complete_signup(
            token=invitation_data["token"],
            password="SecurePassword123!",
            contact_name="John Doe",
            **current_terms_kwargs(),
        )

        users_builder = query_builders["users"]
        users_builder.upsert.assert_called_once()
        profile_payload = users_builder.upsert.call_args.args[0]
        assert profile_payload["id"] == str(mock_user.id)
        assert profile_payload["organization_id"] == invitation_data["organization_id"]
        assert profile_payload["email"] == invitation_data["email"]
        assert profile_payload["full_name"] == "John Doe"
        assert profile_payload["role"] == "tenant"

        lease_link_builder = query_builders["tenant_lease_links"]
        lease_link_builder.insert.assert_called_once()
        lease_link_payload = lease_link_builder.insert.call_args.args[0]
        assert lease_link_payload["tenant_user_id"] == tenant_user_data["id"]
        assert lease_link_payload["lease_id"] == invitation_data["lease_id"]
        assert "id" not in lease_link_payload

