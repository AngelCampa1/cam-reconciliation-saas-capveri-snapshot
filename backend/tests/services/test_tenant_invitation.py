    async def test_token_expired(self, service, mock_admin) -> None:
        """Expired token raises error."""
        invitation_data = make_valid_invitation_data()
        # Set expiration to 7 days ago
        invitation_data["expires_at"] = (
            datetime.now(UTC) - timedelta(days=7)
        ).isoformat()
        mock_result = MagicMock()
        mock_result.data = [invitation_data]
        mock_admin.table.return_value.select.return_value.eq.return_value.execute.return_value = (
            mock_result
        )

        with pytest.raises(InvalidInvitationTokenError) as exc_info:
            await service.validate_token(invitation_data["token"])
        assert "expired" in str(exc_info.value)

    async def test_token_with_timezone_suffix(self, service, mock_admin) -> None:
        """Token expiration with Z suffix is parsed correctly."""
        invitation_data = make_valid_invitation_data()
        # ISO format with Z suffix (use UTC datetime without microseconds to avoid double timezone)
        future_date = datetime.now(UTC) + timedelta(days=7)
        invitation_data["expires_at"] = (
            future_date.replace(microsecond=0).isoformat().replace("+00:00", "Z")
        )
        mock_result = MagicMock()
        mock_result.data = [invitation_data]
        mock_admin.table.return_value.select.return_value.eq.return_value.execute.return_value = (
            mock_result
        )

        result = await service.validate_token(invitation_data["token"])
        assert result == invitation_data


