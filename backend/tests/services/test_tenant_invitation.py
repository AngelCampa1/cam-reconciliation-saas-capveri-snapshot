class TestValidateToken:
    """Tests for validate_token method."""

    async def test_valid_token_success(self, service, mock_admin) -> None:
        """Valid token passes validation."""
        invitation_data = make_valid_invitation_data()
        mock_result = MagicMock()
        mock_result.data = [invitation_data]
        mock_admin.table.return_value.select.return_value.eq.return_value.execute.return_value = (
            mock_result
        )

        # Use the token from the invitation data (UUID format, 36 chars)
        result = await service.validate_token(invitation_data["token"])

        assert result == invitation_data
        mock_admin.table.assert_called_with("tenant_invitations")

    async def test_valid_token_allows_urlsafe_underscore(
        self, service, mock_admin
    ) -> None:
        """Tenant invite validation accepts tokens generated by token_urlsafe."""
        invitation_data = make_valid_invitation_data()
        invitation_data["token"] = "valid_token_with_underscore_1234567890"
        mock_admin.table.return_value.select.return_value.eq.return_value.execute.return_value = MagicMock(
            data=[invitation_data]
        )

        result = await service.validate_token(invitation_data["token"])

        assert result == invitation_data

    async def test_valid_token_uses_admin_client_for_public_signup(
        self, service, mock_db, mock_admin
    ) -> None:
        """Public invitation validation bypasses tenant_invitations RLS safely."""
        invitation_data = make_valid_invitation_data()
        admin_result = MagicMock()
        admin_result.data = [invitation_data]
        mock_admin.table.return_value.select.return_value.eq.return_value.execute.return_value = (
            admin_result
        )

        result = await service.validate_token(invitation_data["token"])

        assert result == invitation_data
        mock_admin.table.assert_called_with("tenant_invitations")
        mock_db.table.assert_not_called()

    async def test_token_not_found(self, service, mock_db) -> None:
        """Token not found raises error."""
        mock_result = MagicMock()
        mock_result.data = []
        mock_db.table.return_value.select.return_value.eq.return_value.execute.return_value = (
            mock_result
        )

        with pytest.raises(InvalidInvitationTokenError) as exc_info:
            await service.validate_token("invalid_token")
